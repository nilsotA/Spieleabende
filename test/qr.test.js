function alsZeilen(matrix) {
  return matrix.map((row) => {
    let s = '';
    let acc = 0;
    let n = 0;
    for (const wert of row) {
      acc = (acc << 1) | (wert ? 1 : 0);
      n++;
      if (n === 4) { s += acc.toString(16); acc = 0; n = 0; }
    }
    if (n) s += (acc << (4 - n)).toString(16);
    return s;
  });
}

for (const fall of VEKTOREN) {
  const kurz = fall.text.length > 26 ? fall.text.slice(0, 26) + '…' : fall.text;
  test(`QR "${kurz}" (${fall.ecl}, Version ${fall.version})`, () => {
    const m = qrMatrix(fall.text, fall.ecl);
    assert.equal(m.length, fall.size, 'Kantenlänge passt nicht zur Version');
    assert.deepEqual(alsZeilen(m), fall.zeilen);
  });
}

test('Version wächst mit der Textlänge', () => {
  assert.equal(qrMatrix('kurz', 'M').length, 21);        // Version 1
  assert.equal(qrMatrix('x'.repeat(60), 'M').length, 33);  // Version 4
  assert.equal(qrMatrix('x'.repeat(200), 'M').length, 57); // Version 10
});

test('zu langer Text wird abgelehnt statt still abgeschnitten', () => {
  assert.throws(() => qrMatrix('x'.repeat(400), 'M'), /zu lang/i);
});

test('Suchmuster sitzen in allen drei Ecken', () => {
  const m = qrMatrix('http://192.168.1.34:3000', 'M');
  const n = m.length;
  for (const [zeile, spalte] of [[0, 0], [0, n - 7], [n - 7, 0]]) {
    assert.equal(m[zeile][spalte], true);
    assert.equal(m[zeile + 1][spalte + 1], false, 'innerer Ring muss hell sein');
    assert.equal(m[zeile + 3][spalte + 3], true, 'Kern muss dunkel sein');
  }
});

test('SVG bringt Rand mit und verweist auf nichts Externes', () => {
  const svg = qrSvg('http://192.168.1.34:3000');
  assert.match(svg, /viewBox="0 0 29 29"/);
  assert.match(svg, /shape-rendering="crispEdges"/);
  assert.ok(!/https?:\/\/(?!www\.w3\.org)/.test(svg), 'keine externen Verweise');
});
